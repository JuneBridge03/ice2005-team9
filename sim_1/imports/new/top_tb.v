`timescale 1ns / 1ps

module top_tb();

    // 1. 입력 및 출력 신호 선언
    reg CLK;
    reg RST;
    wire [6:0] SEG_LED;
    wire [2:0] SEG_DIGIT;
    wire done;
    
    // (선택) 상태 확인용 LED를 top_module에 추가했다면 아래 주석을 해제하세요.
    wire [2:0] LED;

    // 2. 테스트할 Top 모듈 인스턴스화 (UUT: Unit Under Test)
    top_module uut (
        .CLK(CLK), 
        .RST(RST), 
        .SEG_LED(SEG_LED), 
        .SEG_DIGIT(SEG_DIGIT), 
        .done(done),
        .LED(LED)  // LED를 추가했다면 주석 해제
    );

    // ====================================================================
    // 💡 3. 시뮬레이션 속도 단축을 위한 Parameter 덮어쓰기 (defparam)
    // 실제 1초(1억 번)와 세그먼트 스캔(20만 번)을 다 기다리면 시뮬레이션이 
    // 끝나지 않으므로, 카운터 최댓값을 아주 작게 강제로 줄여줍니다.
    // (경로: uut -> disp(디스플레이 모듈) -> 내부 FSM / Driver 이름)
    // ※ 주의: 아래 'fsm_inst'와 'driver_inst' 부분은 실제 display_module 내부에서
    // 인스턴스화 하신 이름과 똑같이 맞춰주셔야 합니다!
    // ====================================================================
    defparam uut.disp.display_fsm.fsm_cnt_max = 27'd5;     // FSM 1초 대기시간 단축
    defparam uut.disp.display_driver.driver_cnt_max = 18'd2; // FND 스캔 속도 단축

    // 4. 클럭(Clock) 생성: 100MHz (주기 10ns)
    initial begin
        CLK = 0;
        forever #5 CLK = ~CLK; 
    end

    // 5. 테스트 시나리오 입력
    initial begin
        // 초기화
        // 보드 버튼은 누르지 않았을 때 1 (Active-Low) 이므로 1로 시작
        RST = 1'b1; 
        
        // 시스템 안정화를 위해 잠시 대기
        #100;
        
        // ----------------------------------------------------
        // [리셋 버튼 누름]
        // ----------------------------------------------------
        RST = 1'b0; // 버튼 누름 (0)
        #100;
        RST = 1'b1; // 버튼 뗌 (1) - 이때부터 연산기 및 컨트롤러 동작 시작

        // ----------------------------------------------------
        // [연산 완료 대기]
        // ----------------------------------------------------
        // 연산기(calc)가 모든 계산을 마치고 done 신호를 1로 올릴 때까지 기다립니다.
        wait(done == 1'b1);
        $display("-----------------------------------------");
        $display("Convolution 연산이 완료되었습니다! (done = 1)");
        $display("-----------------------------------------");

        // ----------------------------------------------------
        // [세그먼트 출력 파형 관찰]
        // ----------------------------------------------------
        // FSM이 돌아가면서 49 -> 57 -> 81 -> 89 값을 순서대로 세그먼트에 
        // 띄워주는 과정을 관찰하기 위해 충분한 시간을 줍니다.
        #10000; 

        $display("시뮬레이션을 종료합니다.");
        $finish; // 시뮬레이션 강제 종료
    end

endmodule