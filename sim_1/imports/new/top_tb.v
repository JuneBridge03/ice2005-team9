`timescale 1ns / 1ps

module top_tb();

    reg CLK;
    reg RST;
    wire [6:0] SEG_LED;
    wire [2:0] SEG_DIGIT;

    always #5 CLK = ~CLK;

    // DUT (Device Under Test) 인스턴스화 및 파라미터 덮어쓰기
    // 원하는 테스트 케이스의 주석을 풀고, 나머지는 주석 처리해서 시뮬레이션
    
    top_module #(
//        // ====================================================================
//        // [Case 1] 기본 제공 데이터 (Overflow 없음)
//        // 기대 결과: 49, 57, 81, 89
//        // ====================================================================
//        .a11(8'd1),  .a12(8'd2),  .a13(8'd3),  .a14(8'd4),
//        .a21(8'd5),  .a22(8'd6),  .a23(8'd7),  .a24(8'd8),
//        .a31(8'd9),  .a32(8'd10), .a33(8'd11), .a34(8'd12),
//        .a41(8'd13), .a42(8'd14), .a43(8'd15), .a44(8'd16),
//        .f11(8'd1),  .f12(8'd2),  .f13(8'd0),
//        .f21(8'd0),  .f22(8'd1),  .f23(8'd1),
//        .f31(8'd2),  .f32(8'd0),  .f33(8'd1)
        
//        // ====================================================================
//        // [Case 2] Overflow + 대칭 필터
//        // 실제 연산합: C11=270, C12=300, C21=330, C22=360
//        // 기대 결과 (하위 8비트 절단):
//        // C11 = 14  (270 % 256)
//        // C12 = 44  (300 % 256)
//        // C21 = 74  (330 % 256)
//        // C22 = 104 (360 % 256)
//        // ====================================================================
//        .a11(8'd30), .a12(8'd30), .a13(8'd30), .a14(8'd40),
//        .a21(8'd30), .a22(8'd30), .a23(8'd30), .a24(8'd40),
//        .a31(8'd30), .a32(8'd30), .a33(8'd30), .a34(8'd40),
//        .a41(8'd50), .a42(8'd50), .a43(8'd50), .a44(8'd60),
        
//        .f11(8'd1), .f12(8'd1), .f13(8'd1),
//        .f21(8'd1), .f22(8'd1), .f23(8'd1),
//        .f31(8'd1), .f32(8'd1), .f33(8'd1)        
        
        
        // ====================================================================
        // [Case 3] Overflow + 비대칭 필터
        //    실제합: C11=1210, C12=1290, C21=1530, C22=1610
        //    기대값: C11=186,  C12=10,   C21=250,  C22=74
        // ====================================================================
        .a11(8'd100), .a12(8'd110), .a13(8'd120), .a14(8'd130),
        .a21(8'd140), .a22(8'd150), .a23(8'd160), .a24(8'd170),
        .a31(8'd180), .a32(8'd190), .a33(8'd200), .a34(8'd210),
        .a41(8'd220), .a42(8'd230), .a43(8'd240), .a44(8'd250),
        
        .f11(8'd1), .f12(8'd2), .f13(8'd0),
        .f21(8'd0), .f22(8'd1), .f23(8'd1),
        .f31(8'd2), .f32(8'd0), .f33(8'd1)
        
        
    ) dut (
        .CLK(CLK),
        .RST(RST),
        .SEG_LED(SEG_LED),
        .SEG_DIGIT(SEG_DIGIT)
    );

    // 시뮬레이션을 위한 디스플레이 FSM/세그먼트 순환 시간 단축
    defparam dut.disp.FSM_MAX = 8;
    defparam dut.disp.DRIVER_MAX = 2;

    // 테스트 시퀀스 입력
    initial begin
        // 초기화
        CLK = 0;
        RST = 0;
        
        // 20ns 후 리셋 해제 (본격적인 동작 시작)
        #20;
        RST = 1;

    end

endmodule
