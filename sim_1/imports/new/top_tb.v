`timescale 1ns / 1ps

module top_tb();

    reg CLK;
    reg RST;
    wire [6:0] SEG_LED;
    wire [2:0] SEG_DIGIT;

    always #5 CLK = ~CLK;

    // DUT (Device Under Test) 인스턴스화 및 파라미터 덮어쓰기
    // 원하는 테스트 케이스의 주석을 풀고, 나머지는 주석 처리해서 시뮬레이션
    
    top_module #(
        // ====================================================================
        // [Case 1] 기본 제공 데이터 (Overflow 없음)
        // 기대 결과: 49, 57, 81, 89
        // ====================================================================
        .a11(8'd1),  .a12(8'd2),  .a13(8'd3),  .a14(8'd4),
        .a21(8'd5),  .a22(8'd6),  .a23(8'd7),  .a24(8'd8),
        .a31(8'd9),  .a32(8'd10), .a33(8'd11), .a34(8'd12),
        .a41(8'd13), .a42(8'd14), .a43(8'd15), .a44(8'd16),
        .f11(8'd1),  .f12(8'd2),  .f13(8'd0),
        .f21(8'd0),  .f22(8'd1),  .f23(8'd1),
        .f31(8'd2),  .f32(8'd0),  .f33(8'd1)
        
        /*
        // ====================================================================
        // [Case 2] 모든 픽셀 값이 1인 이미지 (기본 동작 확인)
        // 필터의 합 = 1+2+0+0+1+1+2+0+1 = 8
        // 기대 결과: 모든 출력 값이 8
        // ====================================================================
        .a11(8'd1), .a12(8'd1), .a13(8'd1), .a14(8'd1),
        .a21(8'd1), .a22(8'd1), .a23(8'd1), .a24(8'd1),
        .a31(8'd1), .a32(8'd1), .a33(8'd1), .a34(8'd1),
        .a41(8'd1), .a42(8'd1), .a43(8'd1), .a44(8'd1),
        .f11(8'd1), .f12(8'd2), .f13(8'd0),
        .f21(8'd0), .f22(8'd1), .f23(8'd1),
        .f31(8'd2), .f32(8'd0), .f33(8'd1)
        */

        /*
        // ====================================================================
        // [Case 3] Black Image (모든 픽셀 0)
        // 기대 결과: 연산 결과가 모두 0으로 출력됨
        // ====================================================================
        .a11(8'd0), .a12(8'd0), .a13(8'd0), .a14(8'd0),
        .a21(8'd0), .a22(8'd0), .a23(8'd0), .a24(8'd0),
        .a31(8'd0), .a32(8'd0), .a33(8'd0), .a34(8'd0),
        .a41(8'd0), .a42(8'd0), .a43(8'd0), .a44(8'd0),
        .f11(8'd1), .f12(8'd2), .f13(8'd0),
        .f21(8'd0), .f22(8'd1), .f23(8'd1),
        .f31(8'd2), .f32(8'd0), .f33(8'd1)
        */

        /*
        // ====================================================================
        // [Case 4] Overflow 테스트 1 (전체 픽셀 최대치 255)
        // 실제 수학적 연산 결과: 255 * 8(필터합) = 2040
        // 기대 결과 (하위 8비트 절단): 2040 % 256 = 248 (8'b11111000)
        // ====================================================================
        .a11(8'd255), .a12(8'd255), .a13(8'd255), .a14(8'd255),
        .a21(8'd255), .a22(8'd255), .a23(8'd255), .a24(8'd255),
        .a31(8'd255), .a32(8'd255), .a33(8'd255), .a34(8'd255),
        .a41(8'd255), .a42(8'd255), .a43(8'd255), .a44(8'd255),
        .f11(8'd1), .f12(8'd2), .f13(8'd0),
        .f21(8'd0), .f22(8'd1), .f23(8'd1),
        .f31(8'd2), .f32(8'd0), .f33(8'd1)
        */

        /*
        // ====================================================================
        // [Case 5] Overflow 테스트 2 (특정 값 초과)
        // 모든 픽셀 50, 필터 모든 값 1 (필터 합 = 9)
        // 실제 수학적 연산 결과: 50 * 9 = 450
        // 기대 결과 (하위 8비트 절단): 450 - 256 = 194 (8'b11000010)
        // ====================================================================
        .a11(8'd50), .a12(8'd50), .a13(8'd50), .a14(8'd50),
        .a21(8'd50), .a22(8'd50), .a23(8'd50), .a24(8'd50),
        .a31(8'd50), .a32(8'd50), .a33(8'd50), .a34(8'd50),
        .a41(8'd50), .a42(8'd50), .a43(8'd50), .a44(8'd50),
        .f11(8'd1), .f12(8'd1), .f13(8'd1),
        .f21(8'd1), .f22(8'd1), .f23(8'd1),
        .f31(8'd1), .f32(8'd1), .f33(8'd1)
        */
    ) dut (
        .CLK(CLK),
        .RST(RST),
        .SEG_LED(SEG_LED),
        .SEG_DIGIT(SEG_DIGIT)
    );

    // 시뮬레이션을 위한 디스플레이 FSM/세그먼트 순환 시간 단축
    defparam dut.disp.FSM_MAX = 5;
    defparam dut.disp.DRIVER_MAX = 2;

    // 테스트 시퀀스 입력
    initial begin
        // 초기화
        CLK = 0;
        RST = 0;
        
        // 20ns 후 리셋 해제 (본격적인 동작 시작)
        #20;
        RST = 1;

        // 연산기가 데이터를 모두 처리하고 디스플레이 FSM이 순환할 때까지 대기
        #100000; 

        $finish; // 시뮬레이션 종료
    end

endmodule