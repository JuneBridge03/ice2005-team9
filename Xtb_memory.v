
`timescale 1ns / 1ps

module tb_memory();

// =========================================================================
    // 1. Input 레지스터 선언 (테스트벤치에서 신호를 만들어 인가할 변수들)
    // =========================================================================
    reg clk;             // 가상의 클럭 신호를 만들 변수
    reg rst;             // 시스템 리셋 신호를 인가할 변수
    reg write;           // 메모리에 데이터를 쓸지 결정하는 활성화 신호
    reg [1:0] sel_mode;  // 연산 모드 선택 (00: Single PE, 01: 3x3 SYS, 10: 2x2 SYS)
    
    // Matrix A Inputs (4x4 구조, 총 16개의 8비트 데이터)
    reg [7:0] A11, A12, A13, A14;
    reg [7:0] A21, A22, A23, A24;
    reg [7:0] A31, A32, A33, A34;
    reg [7:0] A41, A42, A43, A44;
    
    // Filter Matrix F Inputs (3x3 구조, 총 9개의 8비트 데이터)
    reg [7:0] F11, F12, F13;
    reg [7:0] F21, F22, F23;
    reg [7:0] F31, F32, F33;

    // =========================================================================
    // 2. Output 와이어 선언 (메모리 모듈에서 뱉어내는 결과값을 관측할 선)
    // =========================================================================
    // 각 연산 모듈(PE, Systolic Array)로 전달될 A 매트릭스와 F 매트릭스 값
    wire [7:0] A1_out, A2_out, A3_out;
    wire [7:0] F1_out, F2_out, F3_out;
    
    // 연산 모듈을 초기화하기 위한 리셋 신호들
    wire rst_PE, rst_SYS_3x3, rst_SYS_2x2;
    
    // 메모리의 현재 State Machine 상태를 확인하기 위한 관측용 선
    wire [7:0] nextstate;

    // =========================================================================
    // 3. 테스트할 Memory 모듈 인스턴스화 (UUT - Unit Under Test)
    // 실제 만들어둔 memory 모듈을 불러와서 위의 reg, wire들과 핀을 연결.
    // =========================================================================
    memory m3(
        .clk(clk), .rst(rst), .write(write),
        .A11(A11), .A12(A12), .A13(A13), .A14(A14),
        .A21(A21), .A22(A22), .A23(A23), .A24(A24),
        .A31(A31), .A32(A32), .A33(A33), .A34(A34),
        .A41(A41), .A42(A42), .A43(A43), .A44(A44),
        .F11(F11), .F12(F12), .F13(F13),
        .F21(F21), .F22(F22), .F23(F23),
        .F31(F31), .F32(F32), .F33(F33),
        .sel_mode(sel_mode),
        .A1_out(A1_out), .A2_out(A2_out), .A3_out(A3_out),
        .F1_out(F1_out), .F2_out(F2_out), .F3_out(F3_out),
        .rst_PE(rst_PE), .rst_SYS_3x3(rst_SYS_3x3), .rst_SYS_2x2(rst_SYS_2x2),
        .nextstate123(nextstate)
    );

    // =========================================================================
    // 4. 클럭(Clock) 신호 생성
    // =========================================================================
    initial begin
        clk = 0;           // 0초일 때 클럭을 0으로 시작
        forever begin
            #10 clk = ~clk; // 10ns마다 클럭 신호를 반전 (0->1->0...). 즉, 주기는 20ns
        end
    end

    // =========================================================================
    // 5. Matrix A 및 Filter F 초기 데이터 삽입
    // 메모리에 쓰일 가상의 입력 행렬 데이터를 십진수(d)로 1~16, 1~9까지 순서대로 세팅.
    // =========================================================================
    initial begin
        A11=8'd1;  A12=8'd2;  A13=8'd3;  A14=8'd4;
        A21=8'd5;  A22=8'd6;  A23=8'd7;  A24=8'd8;
        A31=8'd9;  A32=8'd10; A33=8'd11; A34=8'd12;
        A41=8'd13; A42=8'd14; A43=8'd15; A44=8'd16;
        
        F11=8'd1;  F12=8'd2;  F13=8'd3;
        F21=8'd4;  F22=8'd5;  F23=8'd6;
        F31=8'd7;  F32=8'd8;  F33=8'd9;
    end

    // =========================================================================
    // 6. 시뮬레이션 동작 시나리오 (Control 신호 인가)
    // 시간에 따라 모드를 바꿔가며 3가지 연산이 모두 잘 작동하는지 파형을 확인.
    // =========================================================================
    initial begin
        // [0ns] 초기화 상태: 리셋을 걸어두고 대기
        rst = 1'b1; write = 1'b0; sel_mode = 2'b11; 
        
        // [100ns] 리셋을 풀고, write를 켜서 8-bit register들에 데이터를 저장.
        // 그리고 sel_mode를 '00'으로 맞춰서 Single PE 모드 연산을 시작함.
        #100 
        rst = 1'b0; 
        write = 1'b1;
        sel_mode = 2'b00; 
        
        // [1060ns] Single PE 연산이 끝날 때까지 960ns 동안 충분히 대기.
        // 이후 sel_mode를 '01'로 바꿔서 3x3 Systolic Array 모드로 진입.
        #960 
        sel_mode = 2'b01; 
        
        // [1840ns] 3x3 연산이 끝날 때까지 780ns 동안 대기.
        // 이후 sel_mode를 '10'으로 바꿔서 2x2 Systolic Array 모드로 진입.
        #780 
        sel_mode = 2'b10; 
        
        // [2540ns] 2x2 연산 결과를 확인할 수 있도록 700ns 더 대기한 후, 시뮬레이션을 강제 종료함.
        #700 
        $stop; 
    end

endmodule

endmodule
